// Two languages, one rule: the ENGLISH string is the key. Display sites wrap
// their text in t('...'), English falls through untouched, and Portuguese
// looks itself up here. A missing entry shows English rather than a blank,
// so a forgotten string is a cosmetic bug, never a broken screen.
//
// Proper nouns stay English in both languages on purpose: Soulfire, Hellpup,
// the Templar and the Time Draught are names, not sentences, and Brazilian
// players have met flavour names in English their whole gaming lives.
//
// Switching language saves and reloads: every string is read at build time,
// so a reload in the new language rebuilds the world already translated.

export let lang = 'en';

export function setLang(code) {
  lang = code === 'pt' ? 'pt' : 'en';
}

/** Translate + fill `{0}`/`{1}` placeholders. */
export function t(text, ...args) {
  let out = lang === 'pt' ? (PT[text] ?? text) : text;
  return args.length ? out.replace(/\{(\d)\}/g, (_, i) => args[i]) : out;
}

